def build_recipes() -> list[dict]:
    out: list[dict] = []
    for cat, dishes in (("한식", KOREAN), ("양식", WESTERN), ("일식", JAPANESE)):
        for title, desc, ings, steps in dishes:
            out.append({"title": title, "category": cat, "description": desc,
                        "ingredients": ings, "steps": steps})
    return out


def main() -> None:
    recipes = build_recipes()
    db = connect(DB_PATH)
    try:
        run_migrations(db)
        owner_id = ensure_user(db)

        counts: dict[str, int] = {}
        for r in recipes:
            counts[r["category"]] = counts.get(r["category"], 0) + 1
        print(f"[시드] DB={DB_PATH or '앱 기본 경로'}")
        print(f"[시드] 레시피 {len(recipes)}건 삽입 시작 "
              f"({', '.join(f'{k} {v}' for k, v in counts.items())})")

        inserted = skipped = 0
        for r in recipes:
            if insert_recipe(db, owner_id, r):
                inserted += 1
            else:
                skipped += 1
                print(f"  · [{r['category']}] {r['title']} — 이미 존재하여 건너뜀")
        db.commit()

        print(f"\n✅ 완료 — 삽입 {inserted}건, 건너뜀 {skipped}건, "
              f"식재료 마스터 {len(_ing_cache)}종")
        print(f"   시드 계정: {SEED_EMAIL} (비밀번호 {SEED_PASSWORD}) 로 로그인하면 '내 레시피'로 보입니다.")
    finally:
        db.close()


if __name__ == "__main__":
    main()
