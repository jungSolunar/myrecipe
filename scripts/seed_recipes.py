def ensure_user(db) -> str:
    """시드 계정을 확보하고 user_id 반환. 없으면 생성."""
    row = db.execute(
        "SELECT id FROM users WHERE email = ? AND deleted_at IS NULL", (SEED_EMAIL,)
    ).fetchone()
    if row:
        print(f"[user] 기존 시드 계정 사용: {SEED_EMAIL}")
        return row["id"]
    uid = new_id("usr")
    now = utcnow()
    db.execute(
        "INSERT INTO users(id, email, password_hash, created_at, updated_at) VALUES (?,?,?,?,?)",
        (uid, SEED_EMAIL, security.hash_password(SEED_PASSWORD), now, now),
    )
    print(f"[user] 시드 계정 생성: {SEED_EMAIL} / 비밀번호: {SEED_PASSWORD}")
    return uid


_ing_cache: dict[str, str] = {}


def ensure_ingredient(db, owner_id: str, name: str, unit: str | None) -> str:
    """식재료 마스터를 이름 기준으로 확보하고 id 반환(소유자 내 활성 유니크)."""
    if name in _ing_cache:
        return _ing_cache[name]
    row = db.execute(
        "SELECT id FROM ingredients WHERE owner_id = ? AND name = ? AND deleted_at IS NULL",
        (owner_id, name),
    ).fetchone()
    if row:
        _ing_cache[name] = row["id"]
        return row["id"]
    iid = new_id("ing")
    now = utcnow()
    db.execute(
        "INSERT INTO ingredients(id, name, category, default_unit, owner_id, created_at, updated_at) "
        "VALUES (?,?,?,?,?,?,?)",
        (iid, name, None, unit, owner_id, now, now),
    )
    _ing_cache[name] = iid
    return iid


def insert_recipe(db, owner_id: str, recipe: dict) -> bool:
    """레시피 1건 삽입. 같은 소유자에 동일 제목이 있으면 건너뜀(True=삽입, False=스킵)."""
    dup = db.execute(
        "SELECT 1 FROM recipes WHERE owner_id = ? AND title = ? AND deleted_at IS NULL",
        (owner_id, recipe["title"]),
    ).fetchone()
    if dup:
        return False

    now = utcnow()
    rid = new_id("rcp")
    db.execute(
        "INSERT INTO recipes(id, title, category, description, photo_url, steps_json, owner_id, created_at, updated_at) "
        "VALUES (?,?,?,?,?,?,?,?,?)",
        (rid, recipe["title"], recipe["category"], recipe["description"], None,
         json.dumps(recipe["steps"], ensure_ascii=False), owner_id, now, now),
    )
    for pos, (name, qty, unit) in enumerate(recipe["ingredients"]):
        ing_id = ensure_ingredient(db, owner_id, name, unit)
        db.execute(
            "INSERT INTO recipe_ingredients(id, recipe_id, ingredient_id, quantity, unit, position, created_at, updated_at) "
            "VALUES (?,?,?,?,?,?,?,?)",
            (new_id("rin"), rid, ing_id, qty, unit, pos, now, now),
        )
    return True


